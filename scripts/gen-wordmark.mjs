/**
 * Generates src/components/Wordmark.astro from the supplied brand artwork.
 *
 * The wordmark ships as a single flat SVG, so the frame and the eight
 * letterforms cannot be animated independently as-is. This script splits them
 * apart and emits a component that keeps the path data verbatim while adding
 * the masks each piece needs to draw itself on.
 *
 * Run from the repo root:  node scripts/gen-wordmark.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const SOURCE = 'public/wellworn-wordmark-dark.svg'
const OUT = 'src/components/Wordmark.astro'

/* -------------------------------------------------------------------------
   Timing. Every letter lands on the same frame as the closing corner of the
   box, so the mark resolves in one beat instead of trailing off.
   ------------------------------------------------------------------------- */
const FRAME_DELAY = 150
const FRAME_DURATION = 1000
/** The moment the whole mark is complete. */
const SETTLE = FRAME_DELAY + FRAME_DURATION
/** Gap between one letter starting and the next. */
const LETTER_STEP = 55
/** Window for the first (longest-drawing) letter. */
const LETTER_WINDOW = 700
/** Keeps mask edges clear of the glyph outlines so nothing clips. */
const PAD = 6

/* -------------------------------------------------------------------------
   Parse
   ------------------------------------------------------------------------- */

const svg = readFileSync(SOURCE, 'utf8')
const ds = [...svg.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1])
if (ds.length !== 9) throw new Error(`expected 9 paths in ${SOURCE}, got ${ds.length}`)

const frame = ds[8]
if (!frame.startsWith('M66.3721 62.5')) throw new Error('last path is not the frame')

/**
 * Bounding box of a path. Every command in this artwork is absolute, and
 * cubic control points are folded in rather than solved for — a bbox that
 * errs large is harmless here, since it only sizes a mask rect.
 */
const bbox = (d) => {
	if (/[mlhvcsqtaz]/.test(d)) throw new Error('relative path commands are not handled')
	let x = 0
	let y = 0
	const box = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity }
	const see = (px, py) => {
		box.minX = Math.min(box.minX, px)
		box.maxX = Math.max(box.maxX, px)
		box.minY = Math.min(box.minY, py)
		box.maxY = Math.max(box.maxY, py)
	}

	for (const [, cmd, rawArgs] of d.matchAll(/([MLHVCZ])([^MLHVCZ]*)/g)) {
		const n = (rawArgs.match(/-?\d*\.?\d+(?:e[-+]?\d+)?/gi) ?? []).map(Number)
		switch (cmd) {
			case 'M':
			case 'L':
				for (let i = 0; i + 1 < n.length; i += 2) see((x = n[i]), (y = n[i + 1]))
				break
			case 'H':
				for (const v of n) see((x = v), y)
				break
			case 'V':
				for (const v of n) see(x, (y = v))
				break
			case 'C':
				for (let i = 0; i + 5 < n.length; i += 6) {
					see(n[i], n[i + 1])
					see(n[i + 2], n[i + 3])
					see((x = n[i + 4]), (y = n[i + 5]))
				}
				break
			case 'Z':
				break
		}
	}
	if (!Number.isFinite(box.minX)) throw new Error('empty bbox')
	return box
}

const round = (v) => Number(v.toFixed(3))

/* Source order runs right-to-left (N first, W last); the stagger has to run
   left-to-right, so rank the glyphs by their leading edge. */
const parsed = ds.slice(0, 8).map((d) => ({ d, box: bbox(d) }))
const order = [...parsed].sort((a, b) => a.box.minX - b.box.minX)

const letters = parsed.map(({ d, box }) => {
	const i = order.indexOf(order.find((p) => p.d === d))
	const duration = LETTER_WINDOW - i * LETTER_STEP
	if (duration <= 0) throw new Error('stagger exceeds the letter window')
	const w = box.maxX - box.minX + PAD * 2
	return {
		d,
		x: round(box.minX - PAD),
		y: round(box.minY - PAD),
		w: round(w),
		h: round(box.maxY - box.minY + PAD * 2),
		duration,
		/* Start late enough that every letter still finishes on SETTLE. */
		delay: SETTLE - duration,
	}
})

const last = Math.max(...letters.map((l) => l.delay + l.duration))
if (last !== SETTLE) throw new Error(`letters settle at ${last}, frame at ${SETTLE}`)

/* -------------------------------------------------------------------------
   Emit
   ------------------------------------------------------------------------- */

const out = `---
/**
 * WELLWORN wordmark, inlined so the frame and letterforms can be animated.
 *
 * GENERATED by scripts/gen-wordmark.mjs — edit that, not this. The path data
 * is copied verbatim from the supplied artwork at ${SOURCE},
 * which stays the source of truth. The dark and light SVGs are identical
 * apart from their hex colour, so this component paints with \`currentColor\`
 * and serves both.
 *
 * On mount the box draws itself clockwise from the top-left while the letters
 * wipe in left to right, staggered ${LETTER_STEP}ms apart but timed to finish
 * together with the box at ${SETTLE}ms.
 */
import { SITE } from '../config/site'

interface Props {
	/** Extra classes for the <svg>. */
	class?: string
	/** Draw the mark on mount. Off by default — opt in where it earns its keep. */
	animate?: boolean
	/**
	 * Prefix for this instance's mask ids. Mask ids are document-global, so
	 * pass a distinct value if a page ever renders more than one wordmark —
	 * otherwise the two sets of masks collide. Kept explicit rather than
	 * generated so the build stays reproducible.
	 */
	id?: string
}

const { class: className = '', animate = false, id: uid = 'wordmark' }: Props = Astro.props

interface Letter {
	readonly d: string
	/** Bounding box of the glyph, padded so the mask never clips an edge. */
	readonly x: number
	readonly y: number
	readonly w: number
	readonly h: number
	readonly duration: number
	readonly delay: number
}

const LETTERS: readonly Letter[] = [
${letters
	.map(
		(l) => `	{
		d: '${l.d}',
		x: ${l.x},
		y: ${l.y},
		w: ${l.w},
		h: ${l.h},
		duration: ${l.duration},
		delay: ${l.delay},
	},`,
	)
	.join('\n')}
]

/** The box: an outer rounded rect with a square inner rect knocked out. */
const FRAME =
	'${frame}'

/**
 * Centreline of the box band, used only as the mask stroke that wipes the box
 * into view. The band runs from the outer edge (55.5) to the inner edge
 * (114.204), so it is 58.71 thick and its centreline sits 29.355 inside the
 * outer rect: 55.5 + 29.355 = 84.855, 62.5 + 29.355 = 91.855, and the far
 * corner likewise 29.355 inside 2419.93 / 533.5.
 */
const FRAME_CENTRELINE = 'M84.855 91.855H2390.575V504.145H84.855Z'
---

<svg
	viewBox="0 0 2476 597"
	width="2476"
	height="597"
	fill="currentColor"
	stroke="currentColor"
	role="img"
	aria-label={SITE.name}
	class={className}
	data-animate={animate ? '' : undefined}
>
	{/*
	  White reveals. The box mask is a stroke along the band's centreline,
	  slightly wider than the 58.71 band so it clears the rounded outer
	  corners — overhang is harmless because a mask only reveals where the
	  frame actually exists. Each letter gets a plain rect that slides in from
	  the left. At rest both sit fully open, so the mark is simply complete.
	*/}
	<mask id={\`\${uid}-frame\`} maskUnits="userSpaceOnUse" x="0" y="0" width="2476" height="597">
		<path d={FRAME_CENTRELINE} class="frame-wipe" fill="none" stroke="#fff" stroke-width="62" />
	</mask>

	{
		LETTERS.map((letter, i) => (
			<mask id={\`\${uid}-letter-\${i}\`} maskUnits="userSpaceOnUse" x="0" y="0" width="2476" height="597">
				<rect
					class="letter-wipe"
					x={letter.x}
					y={letter.y}
					width={letter.w}
					height={letter.h}
					fill="#fff"
					style={\`--wipe:\${letter.w}px;--dur:\${letter.duration}ms;--delay:\${letter.delay}ms\`}
				/>
			</mask>
		))
	}

	{LETTERS.map((letter, i) => <path d={letter.d} mask={\`url(#\${uid}-letter-\${i})\`} />)}

	<path d={FRAME} mask={\`url(#\${uid}-frame)\`} />
</svg>

<style>
	/* One dash the full length of the centreline rect: 2 x (2305.72 + 412.29).
	   \`pathLength\` would avoid the arithmetic but is not honoured by every SVG
	   renderer, so the real perimeter is used. */
	.frame-wipe {
		--frame-length: 5436.02;
		stroke-dasharray: var(--frame-length);
		stroke-dashoffset: 0;
	}

	/* Resting state for both wipes is fully open, so if the animation never
	   runs the mark just renders complete. \`backwards\` holds the start value
	   through the delay instead of flashing the finished mark first. */
	[data-animate] .frame-wipe {
		animation: wordmark-draw ${FRAME_DURATION}ms cubic-bezier(0.65, 0, 0.35, 1) ${FRAME_DELAY}ms backwards;
	}

	[data-animate] .letter-wipe {
		animation: wordmark-wipe var(--dur) cubic-bezier(0.33, 1, 0.68, 1) var(--delay) backwards;
	}

	@keyframes wordmark-draw {
		from {
			stroke-dashoffset: var(--frame-length);
		}
	}

	@keyframes wordmark-wipe {
		from {
			transform: translateX(calc(var(--wipe) * -1));
		}
	}

	/* The global reduce rule collapses duration but not delay, which would
	   still blank the mark for the length of the stagger. Drop it outright. */
	@media (prefers-reduced-motion: reduce) {
		[data-animate] .frame-wipe,
		[data-animate] .letter-wipe {
			animation: none;
		}
	}
</style>
`

writeFileSync(OUT, out)
console.log(
	`wrote ${OUT} — ${letters.length} letters (${LETTER_STEP}ms stagger) + frame, all settling at ${SETTLE}ms`,
)
